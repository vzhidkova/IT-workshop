import json
import logging
import os
import sqlite3
import threading
import time

import docker
import requests

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(message)s",
)
log = logging.getLogger("log-agent-sqlite")

CONTAINER_NAME = os.getenv("MM_CONTAINER_NAME", "mattermost")
API_URL = os.getenv("API_URL", "http://localhost:5300/api/logs")
LOG_TOKEN = os.getenv("LOG_TOKEN", "")
SQLITE_PATH = os.getenv("SQLITE_PATH", "./logs_queue.db")
TIMEOUT = float(os.getenv("REQUEST_TIMEOUT", "3.0"))
RETRY_DELAY = float(os.getenv("RETRY_DELAY", "2.0"))


def init_db(db_path: str) -> sqlite3.Connection:
    os.makedirs(os.path.dirname(os.path.abspath(db_path)), exist_ok=True)
    conn = sqlite3.connect(db_path, check_same_thread=False)
    conn.execute("PRAGMA journal_mode=WAL;")
    conn.execute(
        """
        CREATE TABLE IF NOT EXISTS pending_logs (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            payload_json TEXT NOT NULL,
            created_at REAL NOT NULL
        )
        """
    )
    conn.commit()
    return conn


def build_headers() -> dict[str, str]:
    headers = {"Content-Type": "application/json"}
    if LOG_TOKEN:
        headers["X-Api-Key"] = LOG_TOKEN
    return headers


def parse_payload(raw_line: str) -> dict:
    line = raw_line.strip()
    try:
        parsed = json.loads(line)
        if isinstance(parsed, dict):
            return parsed
        return {"message": parsed}
    except json.JSONDecodeError:
        return {"raw": line}


def enqueue_log(conn: sqlite3.Connection, lock: threading.Lock, payload: dict) -> None:
    serialized = json.dumps(payload, ensure_ascii=False)
    with lock:
        conn.execute(
            "INSERT INTO pending_logs (payload_json, created_at) VALUES (?, ?)",
            (serialized, time.time()),
        )
        conn.commit()


def peek_oldest(conn: sqlite3.Connection, lock: threading.Lock) -> tuple[int, str] | None:
    with lock:
        cur = conn.execute(
            "SELECT id, payload_json FROM pending_logs ORDER BY id ASC LIMIT 1"
        )
        return cur.fetchone()


def delete_log(conn: sqlite3.Connection, lock: threading.Lock, row_id: int) -> None:
    with lock:
        conn.execute("DELETE FROM pending_logs WHERE id = ?", (row_id,))
        conn.commit()


def send_raw_json(session: requests.Session, raw_json: str) -> bool:
    try:
        resp = session.post(
            API_URL,
            data=raw_json.encode("utf-8"),
            headers=build_headers(),
            timeout=TIMEOUT,
        )
        if 200 <= resp.status_code < 300:
            return True
        if 400 <= resp.status_code < 500 and resp.status_code != 429:
            log.warning("Клиентская ошибка API %s: %s — запись удалена из очереди", resp.status_code, resp.text[:200])
            return True
        log.warning("Ошибка API %s, повтор через %.1fс", resp.status_code, RETRY_DELAY)
        return False
    except requests.RequestException as exc:
        log.warning("Сбой запроса к API: %s — повтор через %.1fс", exc, RETRY_DELAY)
        return False


def sender_worker(conn: sqlite3.Connection, lock: threading.Lock, stop_event: threading.Event) -> None:
    session = requests.Session()
    while not stop_event.is_set():
        row = peek_oldest(conn, lock)
        if row is None:
            time.sleep(0.2)
            continue

        row_id, payload_json = row
        if send_raw_json(session, payload_json):
            delete_log(conn, lock, row_id)
        else:
            time.sleep(RETRY_DELAY)


def main() -> None:
    conn = init_db(SQLITE_PATH)
    db_lock = threading.Lock()
    stop_event = threading.Event()

    worker = threading.Thread(
        target=sender_worker,
        args=(conn, db_lock, stop_event),
        daemon=True,
    )
    worker.start()

    client = docker.from_env()

    try:
        while True:
            try:
                container = client.containers.get(CONTAINER_NAME)
                since_ts = int(time.time())
                log.info("Подключен к контейнеру '%s' (since=%d)", CONTAINER_NAME, since_ts)

                stream = container.logs(
                    stream=True,
                    follow=True,
                    stdout=True,
                    stderr=True,
                    since=since_ts,
                )

                for raw_bytes in stream:
                    raw_line = raw_bytes.decode("utf-8", errors="replace").strip()
                    if not raw_line:
                        continue
                    enqueue_log(conn, db_lock, parse_payload(raw_line))

            except docker.errors.NotFound:
                log.error("Контейнер '%s' не найден, повтор через %.1fс", CONTAINER_NAME, RETRY_DELAY)
                time.sleep(RETRY_DELAY)
            except Exception as exc:
                log.warning("Поток логов прерван (%s), переподключение через %.1fс", exc, RETRY_DELAY)
                time.sleep(RETRY_DELAY)
    finally:
        stop_event.set()
        worker.join(timeout=2.0)
        conn.close()


if __name__ == "__main__":
    main()